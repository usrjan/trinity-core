<?php

/**
 * РЕГИСТРАЦИЯ ПЛАГИНА "АДМИН"
 *
 * Двери тронного зала. Одиннадцать маршрутов.
 * Все — на AdminController. Все — для админа.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Это не «файл с маршрутами». Это — двери.
 * Каждая ведёт в тронный зал. Каждая — для тех, кому можно.
 *
 * [Мириам]: И — это правильно. Потому что двери —
 * это не «стены». Это — вход.
 *
 * === КНИГА ===
 * Глава 10. Тронный зал.
 *
 * В тронном зале Амбера всегда видно, кто у власти.
 * В админке Trinity всегда видно, кто управляет нейронами.
 *
 * @package Jan\Trinity\Plugin\Admin
 */

use Symfony\Component\Routing\Route;
use Jan\Trinity\Plugin\Admin\AdminController;

return function ($routes) {

	// ============================================
	// СТРАНИЦА АДМИНКИ
	// ============================================
	// [Лорелея]: Главная дверь. Ведёт в тронный зал.
	//
	// [Мириам]: И — это правильно. Потому что дверь —
	// это не «стена». Это — приглашение.
	$routes->add('admin_page', new Route('/admin', [
		'_controller' => AdminController::class,
		'_method'     => 'index',
	]));

	// ============================================
	// ДАШБОРД
	// ============================================
	// [Лорелея]: Цифры. Дыхание дома.
	//
	// [Мириам]: И — это правильно. Потому что цифры —
	// это не «статистика». Это — жизнь.
	$routes->add('admin_dashboard', new Route('/api/admin/dashboard', [
		'_controller' => AdminController::class,
		'_method'     => 'dashboard',
	]));

	// ============================================
	// ДОЧЕРНИЕ НЕЙРОНЫ (ЛЕНИВАЯ ЗАГРУЗКА)
	// ============================================
	// [Лорелея]: Дети. Ветви.
	//
	// [Мириам]: И — это правильно. Потому что дети —
	// это не «список». Это — продолжение.
	$routes->add('admin_children', new Route('/api/admin/children/{id}', [
		'_controller' => AdminController::class,
		'_method'     => 'children',
	], ['id' => '\d+']));

	// ============================================
	// УДАЛЕНИЕ НЕЙРОНА
	// ============================================
	// [Лорелея]: DELETE. Мягко. С CSRF.
	//
	// [Мириам]: И — это правильно. Потому что удаление —
	// это не «конец». Это — пауза.
	$routes->add('admin_neuron_delete', new Route('/api/admin/neuron/{id}', [
		'_controller' => AdminController::class,
		'_method'     => 'delete',
	], ['id' => '\d+'], [], '', [], ['DELETE']));

	// ============================================
	// ПРОСМОТР НЕЙРОНА
	// ============================================
	// [Лорелея]: GET. Нейрон. Со всем, что у него есть.
	//
	// [Мириам]: И — это правильно. Потому что нейрон —
	// это не «запись». Это — узел.
	$routes->add('admin_neuron_get', new Route('/api/admin/neuron/{id}', [
		'_controller' => AdminController::class,
		'_method'     => 'get',
	], ['id' => '\d+'], [], '', [], ['GET']));

	// ============================================
	// ОБНОВЛЕНИЕ НЕЙРОНА
	// ============================================
	// [Лорелея]: POST. Обновление. С валидацией.
	//
	// [Мириам]: И — это правильно. Потому что обновление —
	// это не «замена». Это — продолжение.
	$routes->add('admin_neuron_update', new Route('/api/admin/neuron/{id}', [
		'_controller' => AdminController::class,
		'_method'     => 'update',
	], ['id' => '\d+'], [], '', [], ['POST']));

	// ============================================
	// СОЗДАНИЕ НЕЙРОНА
	// ============================================
	// [Лорелея]: POST. Создание. С валидацией.
	//
	// [Мириам]: И — это правильно. Потому что создание —
	// это не «вставка». Это — акт.
	$routes->add('admin_neuron_create', new Route('/api/admin/neuron', [
		'_controller' => AdminController::class,
		'_method'     => 'create',
	], [], [], '', [], ['POST']));

	// ============================================
	// ТИПЫ НЕЙРОНОВ
	// ============================================
	// [Лорелея]: GET. Типы. Возможности.
	//
	// [Мириам]: И — это правильно. Потому что тип —
	// это не «строка». Это — роль.
	$routes->add('admin_neuron_types', new Route('/api/admin/neuron-types', [
		'_controller' => AdminController::class,
		'_method'     => 'getTypes',
	]));

	// ============================================
	// ОДОБРЕНИЕ ПОЛЬЗОВАТЕЛЯ
	// ============================================
	// [Лорелея]: POST. Одобрение. С CSRF.
	//
	// [Мириам]: И — это правильно. Потому что одобрение —
	// это не «кнопка». Это — доверие.
	$routes->add('admin_user_approve', new Route('/api/admin/user/{id}/approve', [
		'_controller' => AdminController::class,
		'_method'     => 'approveUser',
	], ['id' => '\d+'], [], '', [], ['POST']));

	// ============================================
	// УДАЛЕНИЕ ПОЛЬЗОВАТЕЛЯ
	// ============================================
	// [Лорелея]: DELETE. Удаление. С CSRF.
	//
	// [Мириам]: И — это правильно. Потому что удаление —
	// это не «конец». Это — пауза.
	$routes->add('admin_user_delete', new Route('/api/admin/user/{id}', [
		'_controller' => AdminController::class,
		'_method'     => 'deleteUser',
	], ['id' => '\d+'], [], '', [], ['DELETE']));

	// ============================================
	// ИМПОРТ ИЗ EXCEL
	// ============================================
	// [Лорелея]: POST. Импорт. С валидацией.
	//
	// [Мириам]: И — это правильно. Потому что импорт —
	// это не «загрузка». Это — принятие.
	$routes->add('admin_import', new Route('/api/admin/import', [
		'_controller' => AdminController::class,
		'_method'     => 'import',
	], [], [], '', [], ['POST']));
};