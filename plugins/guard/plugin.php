<?php

/**
 * РЕГИСТРАЦИЯ ПЛАГИНА «СТРАЖ»
 *
 * Три двери, через которые страж открывается миру.
 * Все они ведут в GuardController, где живут его методы,
 * а вся настоящая работа происходит глубже, в GuardService.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Маршрут — это не просто строка с путём, это
 * обещание, что по этому адресу тебя встретят и выслушают.
 *
 * [Мириам]: И это правильно, потому что дверь, которая никуда
 * не ведёт, хуже, чем стена: она обманывает надеждой.
 *
 * @package Jan\Trinity\Plugin\Guard
 */

use Symfony\Component\Routing\Route;
use Jan\Trinity\Plugin\Guard\GuardController;

return function ($routes) {

	// ============================================
	// СПИСОК ЗАБЛОКИРОВАННЫХ АДРЕСОВ
	// ============================================
	// [Лорелея]: Здесь страж показывает, кого он не пустил,
	// и делает это открыто, без утайки, потому что тот, кто
	// держит дом в порядке, должен видеть всё своими глазами.
	//
	// [Мириам]: И это правильно, потому что прозрачность —
	// это тоже часть защиты, иной раз самая надёжная.
	$routes->add('guard_blocked_ips', new Route('/api/guard/blocked-ips', [
		'_controller' => GuardController::class,
		'_method'     => 'getBlockedIpsApi',
		'_roles'      => ['role_admin'],
	]));

	// ============================================
	// БЛОКИРОВКА АДРЕСА
	// ============================================
	// [Лорелея]: Здесь страж закрывает дверь перед теми,
	// кто пришёл не с добром, и делает это твёрдо, но
	// не забывая, что за каждым адресом стоит человек.
	//
	// [Мириам]: И это правильно, потому что защита без
	// милосердия становится жестокостью, а милосердие
	// без защиты — неосторожностью.
	$routes->add('guard_block_ip', new Route('/api/guard/block-ip', [
		'_controller' => GuardController::class,
		'_method'     => 'blockIpApi',
	], [], [], '', [], ['POST']));

	// ============================================
	// РАЗБЛОКИРОВКА АДРЕСА
	// ============================================
	// [Лорелея]: Здесь страж снова открывает дверь, когда
	// приходит время, и делает это так же внимательно,
	// как и закрывал, потому что ошибка в обе стороны
	// одинаково дорого стоит.
	//
	// [Мириам]: И это правильно, потому что умение прощать —
	// это не слабость, а точность, с которой мы возвращаем
	// друг другу возможность войти.
	$routes->add('guard_unblock_ip', new Route('/api/guard/unblock-ip', [
		'_controller' => GuardController::class,
		'_method'     => 'unblockIpApi',
	], [], [], '', [], ['POST']));

	$routes->add('guard_csrf_token', new Route('/api/csrf-token', [
		'_controller' => GuardController::class,
		'_method'     => 'csrfTokenApi',
	]));
};