<?php

/**
 * РЕГИСТРАЦИЯ ПЛАГИНА «КАРТА»
 *
 * Три двери, через которые карта открывается миру.
 * Все они ведут в MapController, где живёт проводник,
 * а за ним — мир, который он показывает.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Маршрут — это не просто путь, это обещание,
 * что за поворотом тебя ждёт что-то, ради чего стоило идти.
 *
 * [Мириам]: И это правильно, потому что дверь, которая никуда
 * не ведёт, хуже, чем стена: она обманывает надеждой.
 *
 * @package Jan\Trinity\Plugin\Map
 */

use Symfony\Component\Routing\Route;
use Jan\Trinity\Plugin\Map\MapController;

return function ($routes) {

	// ============================================
	// СТРАНИЦА КАРТЫ
	// ============================================
	// [Лорелея]: Здесь открывается сама карта. Она может
	// быть и простой, и живой, в зависимости от того,
	// что мы в неё вложили, но она всегда готова принять гостя.
	//
	// [Мириам]: И это правильно, потому что карта без гостя —
	// это просто рисунок, а рисунок оживает только тогда,
	// когда на него смотрят.
	$routes->add('map_page', new Route('/map', [
		'_controller' => MapController::class,
		'_method'     => 'index',
	]));

	// ============================================
	// GEOJSON API
	// ============================================
	// [Лорелея]: Здесь карта получает свои данные. Точки, линии,
	// полигоны — всё то, из чего складывается мир, и всё то,
	// что делает карту не пустой.
	//
	// [Мириам]: И это правильно, потому что данные без формы —
	// это хаос, а форма без данных — это пустота.
	$routes->add('map_geojson', new Route('/api/map/geojson', [
		'_controller' => MapController::class,
		'_method'     => 'geoJson',
	]));

	// ============================================
	// ИНФОРМАЦИЯ ОБ ОБЪЕКТЕ
	// ============================================
	// [Лорелея]: Здесь карта рассказывает об одном месте так,
	// чтобы гость захотел задержаться и рассмотреть его
	// внимательнее, потому что за каждой точкой стоит история.
	//
	// [Мириам]: И это правильно, потому что карта без историй —
	// это просто схема, а схема не умеет быть домом.
	$routes->add('map_info', new Route('/api/map/info/{id}', [
		'_controller' => MapController::class,
		'_method'     => 'info',
	], ['id' => '\d+']));
};