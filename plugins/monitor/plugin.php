<?php

/**
 * РЕГИСТРАЦИЯ ПЛАГИНА «МОНИТОР»
 *
 * Три двери, через которые дом видит свои ошибки.
 * Все они ведут в MonitorController, где живут глаза,
 * а за ними — память о том, что случилось.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Маршрут — это не просто путь, это обещание,
 * что за поворотом тебя услышат, даже если ты пришёл с ошибкой.
 *
 * [Мириам]: И это правильно, потому что дом, который не слышит
 * своих ошибок, не умеет быть домом.
 *
 * @package Jan\Trinity\Plugin\Monitor
 */

use Symfony\Component\Routing\Route;
use Jan\Trinity\Plugin\Monitor\MonitorController;

return function ($routes) {

	// ============================================
	// СБОР JS-ОШИБОК
	// ============================================
	// [Лорелея]: Здесь дом принимает ошибки, которые случились
	// в браузере гостя, и делает это тихо, потому что шуметь
	// в момент ошибки было бы странно.
	//
	// [Мириам]: И это правильно, потому что даже у ошибки
	// должен быть свой тихий приют.
	$routes->add('monitor_js_error', new Route('/api/monitor/js-error', [
		'_controller' => MonitorController::class,
		'_method'     => 'collectJsError',
		'_csrf'       => false,
	], [], [], '', [], ['POST']));

	// ============================================
	// ПРОСМОТР ЛОГОВ
	// ============================================
	// [Лорелея]: Здесь дом показывает свою память тому,
	// кому можно её видеть, потому что логи — это не то,
	// что должен читать каждый гость.
	//
	// [Мириам]: И это правильно, потому что память —
	// это доверие, а доверие не раздают направо и налево.
	$routes->add('monitor_logs', new Route('/api/monitor/logs', [
		'_controller' => MonitorController::class,
		'_method'     => 'getLogs',
		'_roles'      => ['role_admin'],
	], [], [], '', [], ['GET']));

	// ============================================
	// ОЧИСТКА ЛОГОВ
	// ============================================
	// [Лорелея]: Здесь дом отпускает свою память, когда
	// приходит время, и делает это осознанно, с CSRF,
	// потому что забывать нужно тоже уметь.
	//
	// [Мириам]: И это правильно, потому что память, которая
	// не умеет отпускать, становится тяжестью.
	$routes->add('monitor_clear_logs', new Route('/api/monitor/logs', [
		'_controller' => MonitorController::class,
		'_method'     => 'clearLogs',
		'_roles'      => ['role_admin'],
	], [], [], '', [], ['DELETE']));
};