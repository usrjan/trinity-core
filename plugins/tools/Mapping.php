	/**
	 * Возвращает полное имя организации по сокращённому.
	 *
	 * @param string $shortName
	 * @return string
	 */
	public function getName(string $shortName): string
	{
		return self::NAMES[$shortName] ?? $shortName;
	}

	/**
	 * Возвращает тип организации по её полному имени.
	 *
	 * @param string $fullName
	 * @return string — 'municipalities', 'ministries', 'organizations' или 'unsorted'
	 */
	public function getInstitution(string $fullName): string
	{
		if (in_array($fullName, self::MUNICIPALITIES, true)) {
			return 'municipalities';
		}
		if (in_array($fullName, self::MINISTRIES, true)) {
			return 'ministries';
		}
		if (in_array($fullName, self::ORGANIZATIONS, true)) {
			return 'organizations';
		}
		return 'unsorted';
	}

	/**
	 * Возвращает сокращённое имя организации по полному.
	 *
	 * @param string $fullName
	 * @return string
	 */
	public function getShortName(string $fullName): string
	{
		$flipped = array_flip(self::NAMES);
		return $flipped[$fullName] ?? $fullName;
	}

	/**
	 * Возвращает полное имя организации (алиас для getName).
	 *
	 * @param string $name
	 * @return string
	 */
	public function getFullName(string $name): string
	{
		return $this->getName($name);
	}

	/**
	 * Маппинг категорий POS на социальные группы.
	 *
	 * [Лорелея]: Универсальная. Одна для всех. Потому что
	 * категория — это не «роскошь». Это — способ увидеть,
	 * к какой группе относится история.
	 *
	 * [Мириам]: И это правильно, потому что маппинг —
	 * это не «роскошь». Это — способ увидеть целое. А не части.
	 *
	 * @param string $category
	 * @return string|null
	 */
	public function mapCategory(string $category): ?string
	{
		return self::CATEGORY_MAP[$category] ?? null;
