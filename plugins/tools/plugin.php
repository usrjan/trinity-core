<?php

/**
 * РЕГИСТРАЦИЯ ПЛАГИНА «ИНСТРУМЕНТЫ»
 *
 * Двери в мастерскую: страница инструментов и отчёт по соцсетям.
 * Обе ведут в ToolsController, где живёт мастер.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Это не «файл с маршрутами». Это — двери в мастерскую,
 * и от того, как они открываются, зависит, сможет ли гость войти
 * и сделать работу.
 *
 * [Мириам]: И это правильно, потому что дверь, которая ведёт
 * не туда, хуже, чем стена: она обманывает надеждой.
 *
 * @package Jan\Trinity\Plugin\Tools
 */

use Symfony\Component\Routing\Route;
use Jan\Trinity\Plugin\Tools\ToolsController;

return function ($routes) {

	// ============================================
	// СТРАНИЦА ИНСТРУМЕНТОВ
	// ============================================
	// [Лорелея]: Здесь открывается мастерская, и это правильно,
	// потому что инструменты должны быть видны тому, кто умеет
	// с ними работать.
	//
	// [Мириам]: И это правильно, потому что мастерская — это
	// не «склад», а место, где делают дело.
	$routes->add('tools_page', new Route('/tools', [
		'_controller' => ToolsController::class,
		'_method'     => 'index',
	]));

	// ============================================
	// ОТЧЁТ ПО СОЦСЕТЯМ
	// ============================================
	// [Лорелея]: Здесь мы делаем отчёт, и это правильно,
	// потому что данные должны превращаться в смысл.
	//
	// [Мириам]: И это правильно, потому что отчёт — это
	// не «кнопка», а результат работы.
	$routes->add('tools_report_social', new Route('/api/tools/report-social', [
		'_controller' => ToolsController::class,
		'_method'     => 'reportSocial',
		'_roles'      => ['role_admin'],
	], [], [], '', [], ['POST']));
};