use Jan\Trinity\Core\Kernel;

// Composer — наш проводник в мире зависимостей
require_once __DIR__ . '/../../../autoload.php';

/**
 * Создаём ядро.
 * 
 * Аргумент: путь к корню проекта.
 * Kernel сам найдёт .env, config, plugins.
 * Мы просто говорим: "Проснись".
 */
