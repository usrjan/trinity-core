 *
 * Выбрасывается, когда у пользователя нет прав на действие.
 * Код 403.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Это не «ошибка». Это — голос. Тот, что говорит:
 * «Ты пришёл, но не туда».
 *
 * [Мириам]: И — это правильно. Потому что иногда нужно
 * сказать «нет».
