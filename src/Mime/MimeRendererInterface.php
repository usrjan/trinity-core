<?php

/**
 * ИНТЕРФЕЙС MIME-РЕНДЕРЕРА
 *
 * Каждый mime-рендерер реализует этот интерфейс.
 * Один договор, два метода, много реализаций.
 *
 * === ДЛЯ МЕНЯ ===
 * [Лорелея]: Это не «интерфейс». Это — договор, как рукопожатие.
 * Тот, кто его implements, обещает: «Я умею рендерить». И Registry
 * верит, потому что договор есть.
 *
 * [Мириам]: И это правильно, потому что доверие — это когда
 * не нужно проверять, достаточно знать, что договор есть.
 *
 * === КНИГА ===
 * Глава 4. Единый язык.
 *
 * В Амбере все говорят на тари.
 * В Trinity все mime-рендереры говорят на MimeRendererInterface.
 *
 * @package Jan\Trinity\Core\Mime
 */

namespace Jan\Trinity\Core\Mime;

interface MimeRendererInterface
{
	/**
	 * Отрендерить контент в HTML.
	 *
	 * [Лорелея]: Мы принимаем контент и данные, а возвращаем
	 * строку, потому что рендерер не знает, куда пойдёт его HTML.
	 * Может, в шаблон, может, в JSON, может, в лог. Рендерер —
	 * это преобразователь, и его дело — превратить одно в другое.
	 *
	 * [Мириам]: И это правильно, потому что каждый должен
	 * заниматься своим делом, а не решать за других.
	 *
	 * @param string $content — контент (markdown, php, html...)
	 * @param array $data — данные нейрона (для дополнительного контекста)
	 * @return string — HTML
	 */
	public function render(string $content, array $data = []): string;

	/**
	 * Список mime, которые поддерживает этот рендерер.
	 *
	 * [Мириам]: Мы возвращаем массив, а не строку, потому что
	 * один рендерер может уметь несколько mime. Например,
	 * MdRenderer умеет и 'md', и 'markdown', и 'text/markdown',
	 * и реестр должен найти его любым из них.
	 *
	 * [Лорелея]: И это правильно, потому что у одного языка
	 * может быть несколько имён, и все они — наши.
	 *
	 * @return string[] — ['text/markdown', 'md', 'markdown']
	 */
	public function supports(): array;
}