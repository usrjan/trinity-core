<?php

/**
 * ВАЛИДАТОР ДАННЫХ
 * 
 * Этот класс обеспечивает централизованную проверку всех входящих данных
 * перед их обработкой или сохранением в базу данных.
 * 
 * === НАЗНАЧЕНИЕ ===
 * - Защита целостности базы данных от некорректных данных
 * - Предотвращение SQL-инъекций и XSS-атак на уровне ввода
 * - Унификация правил валидации во всём приложении
 * - Предоставление понятных сообщений об ошибках пользователю
 * 
 * === ПРИНЦИП РАБОТЫ ===
 * 1. Контроллер передаёт данные и правила в метод validate()
 * 2. Validator последовательно применяет каждое правило к каждому полю
 * 3. При нарушении правила сохраняется сообщение об ошибке
 * 4. Если ошибок нет — данные считаются валидными
 * 5. Если есть ошибки — они возвращаются через getErrors()
 * 
 * === ПОДДЕРЖИВАЕМЫЕ ПРАВИЛА ===
 * - required          : Поле обязательно для заполнения (не null и не пустая строка)
 * - nullable          : Поле может содержать null
 * - in:val1,val2,...  : Значение должно быть в списке допустимых
 * - json              : Строка должна быть валидным JSON
 * - exists:table,col  : Запись с таким ID должна существовать в БД
 * - regex:/pattern/   : Значение должно соответствовать регулярному выражению
 * - int               : Значение должно быть целым числом
 * - string            : Значение должно быть строкой (проверяется неявно)
 * - email             : Значение должно быть валидным email (расширение)
 * - min:N             : Минимальная длина строки или значение числа
 * - max:N             : Максимальная длина строки или значение числа
 * 
 * === ДЛЯ РАЗРАБОТЧИКА ===
 * Это второй по важности компонент после логирования.
 * По требованию jan: "Защита от дурака на уровне ядра".
 * Теперь нельзя создать нейрон с битым JSON или пустым типом.
 * 
 * === АНАЛОГИЯ ИЗ КНИГИ ===
 * Глава 5. Страж ворот.
 * 
 * Прежде чем войти в Амбер, нужно пройти через Образ.
 * Прежде чем данные попадут в базу, они проходят через Validator.
 * Только чистые данные достойны хранения в нейронах Trinity.
 */

namespace Jan\Trinity\Core;

class Validator
{
    /** 
     * @var array Массив ошибок валидации
     * Формат: ['field_name' => 'Сообщение об ошибке']
     * Пример: ['email' => 'Поле email обязательно', 'age' => 'age должно быть целым числом']
     */
    private array $errors = [];

    /**
     * Проверить данные по заданным правилам валидации.
     * 
     * Этот метод является основным entry point для валидации.
     * Он очищает предыдущие ошибки и запускает проверку всех полей.
     * 
     * @param array $data — Ассоциативный массив проверяемых данных.
     *                      Ключи — имена полей, значения — сами данные.
     *                      Пример: ['name' => 'John', 'email' => 'john@example.com']
     * 
     * @param array $rules — Ассоциативный массив правил валидации.
     *                       Ключи — имена полей (должны совпадать с $data).
     *                       Значения — массивы правил для каждого поля.
     *                       Пример: [
     *                         'name' => ['required', 'string', 'max:100'],
     *                         'email' => ['required', 'email'],
     *                         'age' => ['nullable', 'int', 'min:18']
     *                       ]
     * 
     * @return bool TRUE если все данные прошли валидацию без ошибок.
     *              FALSE если хотя бы одно поле не прошло проверку.
     * 
     * @example
     * $validator = new Validator();
     * $isValid = $validator->validate(
     *     ['name' => 'John', 'email' => 'invalid'],
     *     ['name' => ['required'], 'email' => ['required', 'email']]
     * );
     * if (!$isValid) { print_r($validator->getErrors()); }
     */
    public function validate(array $data, array $rules): bool
    {
        // Сбрасываем предыдущие ошибки перед новой проверкой
        $this->errors = [];

        // Проходим по каждому правилу для каждого поля
        foreach ($rules as $field => $fieldRules) {
            // Получаем значение поля из данных (или null если отсутствует)
            $value = $data[$field] ?? null;

            // Применяем каждое правило последовательно
            foreach ($fieldRules as $rule) {
                $this->applyRule($field, $value, $rule, $data);
            }
        }

        // Возвращаем true только если массив ошибок пуст
        return empty($this->errors);
    }

    /**
     * Применить одно правило валидации к одному полю.
     * 
     * Этот метод инкапсулирует логику проверки отдельных правил.
     * Вызывается многократно из метода validate() для каждого правила.
     * 
     * @param string $field — Имя проверяемого поля (для сообщений об ошибках).
     *                        Пример: 'email', 'password', 'user_id'
     * 
     * @param mixed $value — Значение поля для проверки.
     *                       Может быть любого типа: string, int, null, array и т.д.
     * 
     * @param string $rule — Строковое представление правила.
     *                        Примеры: 'required', 'in:admin,user', 'regex:/^[a-z]+$/'
     * 
     * @param array $data — Полный массив исходных данных.
     *                      Передаётся для правил, требующих доступа к другим полям
     *                      (например, confirmed для проверки совпадения паролей).
     * 
     * @return void Результат сохраняется в $this->errors.
     */
    private function applyRule(string $field, $value, string $rule, array $data): void
    {
        // ============================================
        // ПРАВИЛО: required
        // Поле обязательно для заполнения.
        // Не проходит проверку если: null или пустая строка ''.
        // ============================================
        if ($rule === 'required' && ($value === null || $value === '')) {
            $this->errors[$field] = "Поле '{$field}' обязательно для заполнения";
            return; // Прерываем дальнейшую проверку этого поля
        }

        // ============================================
        // ПРАВИЛО: nullable
        // Поле может содержать null.
        // Если значение null — остальные правила не проверяются.
        // ============================================
        if ($rule === 'nullable' && $value === null) {
            return; // Пропускаем дальнейшую проверку, null допустим
        }

        // ============================================
        // ПРАВИЛО: in:value1,value2,...
        // Значение должно быть в списке допустимых.
        // Пример: in:active,pending,closed
        // ============================================
        if (str_starts_with($rule, 'in:')) {
            // Извлекаем список допустимых значений после префикса 'in:'
            $allowed = explode(',', substr($rule, 3));
            // Строгая проверка типа (true означает строгое сравнение ===)
            if (!in_array($value, $allowed, true)) {
                $this->errors[$field] = "Недопустимое значение для '{$field}'. " .
                                        "Разрешено: " . implode(', ', $allowed);
            }
        }

        // ============================================
        // ПРАВИЛО: json
        // Строка должна быть валидным JSON.
        // Проверяется только если значение не null.
        // ============================================
        if ($rule === 'json' && $value !== null) {
            if (is_string($value)) {
                // Пытаемся декодировать JSON
                json_decode($value);
                // Проверяем наличие ошибок декодирования
                if (json_last_error() !== JSON_ERROR_NONE) {
                    $this->errors[$field] = "Поле '{$field}' должно содержать валидный JSON. " .
                                            "Ошибка: " . json_last_error_msg();
                }
            } else {
                // Если значение не строка — это точно не JSON
                $this->errors[$field] = "Поле '{$field}' должно быть строкой в формате JSON";
            }
        }

        // ============================================
        // ПРАВИЛО: exists:table,column
        // Запись с таким значением должна существовать в базе данных.
        // Пример: exists:users,id (проверка существования пользователя)
        // Примечание: Реальная проверка БД должна быть в репозитории.
        // ============================================
        if (str_starts_with($rule, 'exists:')) {
            // Парсим правило: exists:table,column
            $params = explode(',', substr($rule, 7));
            $table = $params[0] ?? 'neuron';
            $column = $params[1] ?? 'id';
            
            // Здесь могла бы быть проверка БД через репозиторий
            // Но для избежания циклических зависимостей проверка выносится в репозитории
            // Логика: $db->exists($table, $column, $value)
        }

        // ============================================
        // ПРАВИЛО: regex:/pattern/
        // Значение должно соответствовать регулярному выражению.
        // Пример: regex:/^[a-zA-Z0-9_]+$/ (только латиница, цифры, подчёркивание)
        // ============================================
        if (str_starts_with($rule, 'regex:')) {
            // Извлекаем паттерн после префикса 'regex:'
            $pattern = substr($rule, 6);
            // Преобразуем значение к строке для проверки
            if (!preg_match($pattern, (string) $value)) {
                $this->errors[$field] = "Поле '{$field}' не соответствует требуемому формату";
            }
        }

        // ============================================
        // ПРАВИЛО: int
        // Значение должно быть целым числом.
        // Проверяются как native int, так и строки из цифр.
        // ============================================
        if ($rule === 'int' && !is_int($value) && !ctype_digit((string) $value)) {
            $this->errors[$field] = "Поле '{$field}' должно быть целым числом";
        }

        // ============================================
        // ПРАВИЛО: string
        // Значение должно быть строкой.
        // Неявная проверка для документирования требований.
        // ============================================
        if ($rule === 'string' && !is_string($value) && $value !== null) {
            $this->errors[$field] = "Поле '{$field}' должно быть строкой";
        }

        // ============================================
        // ПРАВИЛО: email
        // Значение должно быть валидным email адресом.
        // Используется встроенный фильтр PHP.
        // ============================================
        if ($rule === 'email' && $value !== null) {
            if (!filter_var($value, FILTER_VALIDATE_EMAIL)) {
                $this->errors[$field] = "Поле '{$field}' должно быть валидным email адресом";
            }
        }

        // ============================================
        // ПРАВИЛО: min:N
        // Минимальная длина строки или минимальное значение числа.
        // Пример: min:5 (минимум 5 символов или значение >= 5)
        // ============================================
        if (str_starts_with($rule, 'min:')) {
            $min = (int) substr($rule, 4);
            if (is_string($value) && strlen($value) < $min) {
                $this->errors[$field] = "Поле '{$field}' должно содержать минимум {$min} символов";
            } elseif (is_numeric($value) && $value < $min) {
                $this->errors[$field] = "Значение '{$field}' должно быть не менее {$min}";
            }
        }

        // ============================================
        // ПРАВИЛО: max:N
        // Максимальная длина строки или максимальное значение числа.
        // Пример: max:255 (максимум 255 символов или значение <= 255)
        // ============================================
        if (str_starts_with($rule, 'max:')) {
            $max = (int) substr($rule, 4);
            if (is_string($value) && strlen($value) > $max) {
                $this->errors[$field] = "Поле '{$field}' должно содержать максимум {$max} символов";
            } elseif (is_numeric($value) && $value > $max) {
                $this->errors[$field] = "Значение '{$field}' должно быть не более {$max}";
            }
        }
    }

    /**
     * Получить все ошибки валидации.
     * 
     * Возвращает ассоциативный массив, где ключи — имена полей,
     * а значения — сообщения об ошибках для этих полей.
     * 
     * @return array Массив ошибок формата [поле => сообщение].
     *               Пустой массив если валидация прошла успешно.
     * 
     * @example
     * $errors = $validator->getErrors();
     * // ['email' => 'Поле email обязательно', 'age' => 'age должно быть целым числом']
     */
    public function getErrors(): array
    {
        return $this->errors;
    }

    /**
     * Проверить наличие ошибок и выбросить исключение при необходимости.
     * 
     * Удобный метод для использования в контроллерах и сервисах.
     * Вместо ручной проверки getErrors() можно вызвать этот метод.
     * 
     * @return void
     * 
     * @throws ValidationException Если есть хотя бы одна ошибка валидации.
     *                             Исключение содержит массив всех ошибок.
     * 
     * @example
     * $validator->validate($data, $rules);
     * $validator->throwIfInvalid(); // Выбросит исключение если есть ошибки
     * // Дальнейший код выполняется только если данные валидны
     */
    public function throwIfInvalid(): void
    {
        if (!empty($this->errors)) {
            // Создаём и выбрасываем исключение с полным списком ошибок
            throw new ValidationException($this->errors);
        }
    }

    /**
     * Проверить, прошла ли валидация без ошибок.
     * 
     * Удобный метод для быстрой проверки результата.
     * 
     * @return bool TRUE если ошибок нет, FALSE если есть ошибки.
     */
    public function isValid(): bool
    {
        return empty($this->errors);
    }

    /**
     * Добавить пользовательскую ошибку валидации.
     * 
     * Полезно для сложных правил, которые невозможно выразить
     * через стандартные правила (например, перекрёстная проверка полей).
     * 
     * @param string $field — Имя поля, к которому относится ошибка.
     * @param string $message — Сообщение об ошибке.
     * @return self Возвращает $this для цепочки вызовов (fluent interface).
     */
    public function addError(string $field, string $message): self
    {
        $this->errors[$field] = $message;
        return $this;
    }
}

/**
 * ИСКЛЮЧЕНИЕ ВАЛИДАЦИИ
 * 
 * Специализированное исключение для ошибок валидации данных.
 * Содержит полный массив ошибок для передачи клиенту.
 * 
 * === НАЗНАЧЕНИЕ ===
 * - Отделить ошибки валидации от других типов ошибок
 * - Передать структурированный список ошибок клиенту
 * - Обеспечить единый формат обработки ошибок валидации
 * 
 * === ПРИМЕР ИСПОЛЬЗОВАНИЯ ===
 * try {
 *     $validator->validate($data, $rules);
 *     $validator->throwIfInvalid();
 * } catch (ValidationException $e) {
 *     return ApiResponse::error($e->getMessage(), 422);
 *     // Или вернуть детализированные ошибки:
 *     // return ApiResponse::error('Ошибка валидации', 422)
 *     //        ->setData(['errors' => $e->getErrors()]);
 * }
 */
class ValidationException extends \RuntimeException
{
    /** 
     * @var array Массив ошибок валидации
     * Формат: ['field_name' => 'Сообщение об ошибке']
     */
    private array $errors;

    /**
     * Конструктор исключения валидации.
     * 
     * @param array $errors — Массив ошибок от Validator.
     *                       Каждая ошибка становится частью сообщения исключения.
     */
    public function __construct(array $errors)
    {
        $this->errors = $errors;
        
        // Формируем человекочитаемое сообщение из всех ошибок
        // Пример: "Поле email обязательно; Поле age должно быть целым числом"
        $message = implode('; ', $errors);
        
        // Вызываем конструктор родительского класса с собранным сообщением
        parent::__construct($message, 422); // HTTP 422 Unprocessable Entity
    }

    /**
     * Получить массив ошибок валидации.
     * 
     * @return array Массив ошибок формата [поле => сообщение].
     * 
     * @example
     * catch (ValidationException $e) {
     *     $errors = $e->getErrors();
     *     // ['email' => 'Поле email обязательно']
     * }
     */
    public function getErrors(): array
    {
        return $this->errors;
    }
}